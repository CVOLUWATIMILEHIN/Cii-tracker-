export function exportWeeklyReportsPdf(
  reports: WeeklyReport[],
  generatedBy: string,
  role: CanonicalRole
): void {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, doc.internal.pageSize.getWidth(), 72, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('CII Accountability Tracker — Weekly Accountability Reports', 40, 34);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(203, 213, 225);
  doc.text(
    `Generated by ${generatedBy} (${ROLE_LABELS[role]}) · ${new Date().toLocaleString()} · ${reports.length} reports`,
    40,
    54
  );

  autoTable(doc, {
    startY: 92,
    head: [['Week', 'Member', 'Status', 'Achievements', 'Challenges', 'Next Priorities', 'Feedback']],
    body: reports.map((r) => [
      r.weekLabel,
      r.memberName,
      REPORT_STATUS_LABELS[r.status],
      r.achievements.slice(0, 120),
      r.challenges.slice(0, 100),
      r.nextWeekPriorities.slice(0, 100),
      r.feedbackText ? r.feedbackText.slice(0, 80) : '—',
    ]),
    styles: { fontSize: 8.5, cellPadding: 5 },
    headStyles: { fillColor: [30, 41, 59], textColor: [255, 255, 255] },
    alternateRowStyles: { fillColor: [248, 250, 252] },
    margin: { left: 40, right: 40 },
  });

  doc.save(`cii-weekly-reports-${formatDateTag()}.pdf`);
}

export function exportActivitiesCsv(
  activities: Activity[],
  submissions: ActivitySubmission[]
): void {
  const headers = ['Code', 'Title', 'Pillar', 'Cohort', 'Scope', 'Deadline', 'Status', 'Submissions'];
  const rows = activities.map((a) => [
    a.code,
    a.title,
    a.pillar,
    a.cohortName || 'All Cohorts',
    a.assignmentScope,
    a.deadline,
    a.status.toUpperCase(),
    submissions.filter((s) => s.activityId === a.id).length,
  ]);
  const csv = [headers, ...rows].map((r) => r.map(escapeCsvCell).join(',')).join('\r\n');
  downloadBlob(`\uFEFF${csv}`, `cii-activities-${formatDateTag()}.csv`, 'text/csv;charset=utf-8;');
}

